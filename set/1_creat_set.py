# Exercise 1: Create a set and add elements

def create_add_simple():
    my_set = set()
    my_set.add(1)
    my_set.add(2)
    my_set.add(3)
    print("Set after adding:", my_set)

def create_with_braces():
    my_set = {1, 2, 3}
    print("Set using braces:", my_set)

# Example
create_add_simple()
create_with_braces()